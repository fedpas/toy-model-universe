#!/bin/sh
# Re-run the timing of the label claims on THIS machine and rebuild the data module the page shows next to the visitor's own timing.
# (The numbers differ from machine to machine and from run to run; the page prints this machine's description with them.)
set -e
cd "$(dirname "$0")"
node bench_labels.mjs --write bench_labels.json
node -e "const fs=require('fs');const d=JSON.parse(fs.readFileSync('bench_labels.json','utf8'));fs.writeFileSync('../benchData.js','// generated by selfcheck/regen_bench.sh from bench_labels.json; do not edit\nexport default '+JSON.stringify(d)+';\n')"
mkdir -p /home/claude/ui/selfcheck && cp bench_labels.mjs bench_labels.json /home/claude/ui/selfcheck/ 2>/dev/null || true
